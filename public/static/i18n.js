const LANG_KEY = "ia-lang";
let currentLang = (() => {
  try { return localStorage.getItem(LANG_KEY) || "en"; } catch { return "en"; }
})();

function t(key, vars = {}) {
  const raw = (STRINGS[currentLang] && STRINGS[currentLang][key]) ?? STRINGS.en[key] ?? key;
  return raw.replace(/\{(\w+)\}/g, (_, name) => (vars[name] ?? `{${name}}`));
}

function setLanguage(lang) {
  currentLang = STRINGS[lang] ? lang : "en";
  try { localStorage.setItem(LANG_KEY, currentLang); } catch { /* private mode */ }
  document.documentElement.lang = currentLang;
  for (const node of document.querySelectorAll("[data-i18n]")) node.textContent = t(node.dataset.i18n);
  for (const node of document.querySelectorAll("[data-i18n-ph]")) node.placeholder = t(node.dataset.i18nPh);
  for (const node of document.querySelectorAll("[data-i18n-aria]")) node.setAttribute("aria-label", t(node.dataset.i18nAria));
  document.title = t("app.name");
}

